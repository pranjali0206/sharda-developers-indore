/**
 * Image pipeline. Reads originals from public/assets, writes responsive AVIF/WebP
 * variants to public/assets/optimized, OG cards + favicons to public/, and a typed
 * manifest (src/generated/images.ts) that the <Img> component reads.
 *
 * Swapping in hi-res originals from the client = drop the file in public/assets with
 * the same name and re-run `npm run images`. Larger widths are generated automatically.
 */
import { readdir, mkdir, stat, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'public/assets');
const OUT = path.join(SRC, 'optimized');
const PHOTO_WIDTHS = [480, 768, 1200, 1600, 2000];
const LOGO_WIDTHS = [200, 400, 800];

const isLogo = (name) => name.includes('logo') || name.includes('mark');

async function newer(src, out) {
  try {
    const [a, b] = await Promise.all([stat(src), stat(out)]);
    return b.mtimeMs >= a.mtimeMs;
  } catch {
    return false;
  }
}

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png)$/i.test(f));
const manifest = {};

for (const file of files) {
  const name = file.replace(/\.(jpe?g|png)$/i, '');
  const src = path.join(SRC, file);
  const meta = await sharp(src).metadata();
  const base = isLogo(name) ? LOGO_WIDTHS : PHOTO_WIDTHS;
  let widths = base.filter((w) => w <= meta.width);
  if (!widths.length || (widths.at(-1) < meta.width && widths.at(-1) < base.at(-1))) {
    widths.push(Math.min(meta.width, base.at(-1)));
  }
  widths = [...new Set(widths)].sort((a, b) => a - b);

  for (const w of widths) {
    for (const fmt of ['avif', 'webp']) {
      const out = path.join(OUT, `${name}-${w}.${fmt}`);
      if (await newer(src, out)) continue;
      const img = sharp(src).resize({ width: w, withoutEnlargement: true });
      if (fmt === 'avif')
        await img.avif({ quality: isLogo(name) ? 70 : 52, effort: 5 }).toFile(out);
      else await img.webp({ quality: isLogo(name) ? 90 : 78, effort: 5 }).toFile(out);
    }
  }
  manifest[name] = {
    src: `/assets/${file}`,
    width: meta.width,
    height: meta.height,
    widths,
    alpha: Boolean(meta.hasAlpha),
  };
  console.warn(`✓ ${name} ${meta.width}×${meta.height} → ${widths.join('/')}`);
}

// Prune variants that no longer belong to any source (replaced or removed originals).
const expected = new Set(
  Object.entries(manifest).flatMap(([name, m]) =>
    m.widths.flatMap((w) => [`${name}-${w}.avif`, `${name}-${w}.webp`]),
  ),
);
for (const f of await readdir(OUT)) {
  if (!expected.has(f)) {
    await unlink(path.join(OUT, f));
    console.warn(`pruned ${f}`);
  }
}

// Open Graph / Twitter cards (1200×630).
const og = {
  'og-home': 'paradise-gate.jpg',
  'og-paradise': 'paradise-gate.jpg',
  'og-greens': 'greens-gate.jpg',
};
for (const [name, from] of Object.entries(og)) {
  await sharp(path.join(SRC, from))
    .resize(1200, 630, { fit: 'cover', position: 'attention' })
    .jpeg({ quality: 82, progressive: true, mozjpeg: true })
    .toFile(path.join(ROOT, 'public', `${name}.jpg`));
}

// Favicons from the Sharda Developers building mark.
const mark = path.join(SRC, 'sharda-developers-mark.png');
await sharp(mark)
  .resize(64, 64, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .png()
  .toFile(path.join(ROOT, 'public/favicon.png'));
await sharp(mark)
  .resize(140, 140, { fit: 'contain', background: '#ffffff' })
  .extend({ top: 20, bottom: 20, left: 20, right: 20, background: '#ffffff' })
  .png()
  .toFile(path.join(ROOT, 'public/apple-touch-icon.png'));

await mkdir(path.join(ROOT, 'src/generated'), { recursive: true });
const ts = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
export const images = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof images;
`;
await writeFile(path.join(ROOT, 'src/generated/images.ts'), ts);
console.warn(`Wrote manifest for ${Object.keys(manifest).length} images.`);
